CREATE TABLE career
(
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code VARCHAR(20)                              NOT NULL,
    name VARCHAR(120)                             NOT NULL,
    CONSTRAINT pk_career PRIMARY KEY (id),
    CONSTRAINT uq_career_code UNIQUE (code)
);

CREATE TABLE student
(
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    identification VARCHAR(20)                              NOT NULL,
    first_name     VARCHAR(80)                              NOT NULL,
    last_name      VARCHAR(80)                              NOT NULL,
    email          VARCHAR(120),
    career_id      INTEGER                                  NOT NULL,
    CONSTRAINT pk_student PRIMARY KEY (id),
    CONSTRAINT uq_student_identification UNIQUE (identification),
    CONSTRAINT fk_student_career FOREIGN KEY (career_id) REFERENCES career (id)
);

CREATE TABLE academic_period
(
    id     INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code   VARCHAR(20)                              NOT NULL,
    name   VARCHAR(120)                             NOT NULL,
    active BOOLEAN                                  NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_academic_period PRIMARY KEY (id),
    CONSTRAINT uq_academic_period_code UNIQUE (code)
);

CREATE TABLE subject
(
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code    VARCHAR(20)                              NOT NULL,
    name    VARCHAR(120)                             NOT NULL,
    credits INTEGER                                  NOT NULL DEFAULT 0,
    CONSTRAINT pk_subject PRIMARY KEY (id),
    CONSTRAINT uq_subject_code UNIQUE (code)
);

CREATE TABLE teacher
(
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    identification VARCHAR(20)                              NOT NULL,
    first_name     VARCHAR(80)                              NOT NULL,
    last_name      VARCHAR(80)                              NOT NULL,
    email          VARCHAR(120),
    CONSTRAINT pk_teacher PRIMARY KEY (id),
    CONSTRAINT uq_teacher_identification UNIQUE (identification)
);

-- Curso/paralelo: una asignatura, dada por un docente, en un periodo
CREATE TABLE course
(
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    subject_id INTEGER                                  NOT NULL,
    teacher_id INTEGER                                  NOT NULL,
    period_id  INTEGER                                  NOT NULL,
    parallel   VARCHAR(5)                               NOT NULL DEFAULT 'A',
    CONSTRAINT pk_course PRIMARY KEY (id),
    CONSTRAINT uq_course UNIQUE (subject_id, period_id, parallel),
    CONSTRAINT fk_course_subject FOREIGN KEY (subject_id) REFERENCES subject (id),
    CONSTRAINT fk_course_teacher FOREIGN KEY (teacher_id) REFERENCES teacher (id),
    CONSTRAINT fk_course_period FOREIGN KEY (period_id) REFERENCES academic_period (id)
);

-- Matricula: un estudiante inscrito en un curso
CREATE TABLE enrollment
(
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    student_id  INTEGER                                  NOT NULL,
    course_id   INTEGER                                  NOT NULL,
    enrolled_at TIMESTAMP                                NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_enrollment PRIMARY KEY (id),
    CONSTRAINT uq_enrollment UNIQUE (student_id, course_id),
    CONSTRAINT fk_enrollment_student FOREIGN KEY (student_id) REFERENCES student (id),
    CONSTRAINT fk_enrollment_course FOREIGN KEY (course_id) REFERENCES course (id)
);

-- Calificacion: una nota por matricula, entre 0 y 10
CREATE TABLE grade
(
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    enrollment_id INTEGER                                  NOT NULL,
    score         NUMERIC(4, 2)                            NOT NULL,
    registered_at TIMESTAMP                                NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_grade PRIMARY KEY (id),
    CONSTRAINT uq_grade_enrollment UNIQUE (enrollment_id),
    CONSTRAINT ck_grade_score CHECK (score BETWEEN 0 AND 10),
    CONSTRAINT fk_grade_enrollment FOREIGN KEY (enrollment_id) REFERENCES enrollment (id)
);

CREATE INDEX idx_student_career ON student (career_id);
CREATE INDEX idx_period_active ON academic_period (active);
CREATE INDEX idx_course_subject ON course (subject_id);
CREATE INDEX idx_course_period ON course (period_id);
CREATE INDEX idx_enroll_student ON enrollment (student_id);
CREATE INDEX idx_enroll_course ON enrollment (course_id);

-- Vista para reportes (la usa GradeReport)
CREATE VIEW v_grade_report AS
SELECT g.id                               AS grade_id,
       s.id                               AS student_id,
       s.first_name || ' ' || s.last_name AS student_name,
       ca.id                              AS career_id,
       ca.code                            AS career_code,
       ca.name                            AS career_name,
       sub.id                             AS subject_id,
       sub.code                           AS subject_code,
       sub.name                           AS subject_name,
       p.id                               AS period_id,
       p.code                             AS period_code,
       g.score::float8                    AS score
FROM grade g
         JOIN enrollment e ON e.id = g.enrollment_id
         JOIN student s ON s.id = e.student_id
         JOIN career ca ON ca.id = s.career_id
         JOIN course c ON c.id = e.course_id
         JOIN subject sub ON sub.id = c.subject_id
         JOIN academic_period p ON p.id = c.period_id;
